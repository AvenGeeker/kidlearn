--[[--
Knowledge-point graph and question-bank loading for KidLearn.

Data is generated by tools/kidlearn/sync_taxonomy.py from cn-math-taxonomy
(CC BY-NC 4.0).  Volume files live under data/knowledge/<subject>/g<N>{u,l}.json
and hold topic metadata plus normalized questions; <subject>_graph.json holds
the prerequisite graph.  This module mirrors core/bank.lua's caching style but
accepts 3-4 option choices and fraction answers, which the synced bank uses.
--]]--

local JSON = require("json")
local logger = require("logger")
local util = require("util")

local Knowledge = {}

local graph_cache = {}
local volume_cache = {}

local function read_json(path)
    local content, err = util.readFromFile(path, "rb")
    if not content then return nil, err or ("cannot read " .. path) end
    local ok, data = pcall(JSON.decode, content)
    if not ok or type(data) ~= "table" then
        return nil, tostring(data or "invalid JSON")
    end
    return data
end

local function volume_path(plugin_path, subject, grade, semester)
    return string.format("%s/data/knowledge/%s/g%d%s.json",
        plugin_path, subject, grade, semester == "lower" and "l" or "u")
end

local function normalize_options(options)
    if type(options) ~= "table" then return nil end
    if #options < 3 or #options > 4 then return nil end
    local seen = {}
    for _, option in ipairs(options) do
        if type(option) ~= "string" or option == "" then return nil end
        if seen[option] then return nil end
        seen[option] = true
    end
    return options
end

local function normalize_question(raw)
    if type(raw) ~= "table" then return nil, "not a table" end
    if type(raw.id) ~= "string" or raw.id == "" then return nil, "missing id" end
    if type(raw.topic) ~= "string" or raw.topic == "" then return nil, "missing topic" end
    if type(raw.stem) ~= "string" or raw.stem == "" then return nil, "missing stem" end
    if type(raw.explain) ~= "string" or raw.explain == "" then return nil, "missing explain" end

    local difficulty = tonumber(raw.difficulty) or 1
    if difficulty < 1 then difficulty = 1 elseif difficulty > 3 then difficulty = 3 end

    local q = {
        id = raw.id,
        topic = raw.topic,
        subject = raw.subject,
        grade = tonumber(raw.grade),
        semester = raw.semester == "lower" and "lower" or "upper",
        edition = raw.edition,
        unit = raw.unit,
        unit_name = raw.unit_name,
        type = type(raw.type) == "string" and raw.type or "knowledge",
        skill = type(raw.skill) == "string" and raw.skill or "knowledge",
        difficulty = difficulty,
        answer_mode = raw.answer_mode == "number" and "number" or "choice",
        stem = raw.stem,
        explain = raw.explain,
    }

    if q.answer_mode == "number" then
        local format = raw.answer_format
        if format == "fraction" then
            local num, den = tostring(raw.answer or ""):match("^(%d+)/(%d+)$")
            if not num or tonumber(den) == 0 then return nil, "bad fraction answer" end
            q.answer_format = "fraction"
            q.answer = num .. "/" .. den
        elseif format == "decimal" then
            local answer = tonumber(raw.answer)
            if not answer or answer < 0 then return nil, "bad decimal answer" end
            q.answer_format = "decimal"
            q.answer = answer
        else
            local answer = tonumber(raw.answer)
            if not answer or answer < 0 or answer % 1 ~= 0 then return nil, "bad integer answer" end
            q.answer_format = "integer"
            q.answer = answer
        end
    else
        local options = normalize_options(raw.options)
        if not options then return nil, "choice needs 3-4 unique options" end
        local answer = tonumber(raw.answer)
        if not answer or answer < 1 or answer > #options or answer % 1 ~= 0 then
            return nil, "invalid answer index"
        end
        q.options = options
        q.answer = answer
    end
    return q
end

--[[--
Load the prerequisite graph for a subject.
@treturn table {nodes, order, prereqs, dependents, edges} or nil, err
--]]--
function Knowledge.graph(plugin_path, subject)
    if not plugin_path or plugin_path == "" then return nil, "plugin path missing" end
    subject = subject or "math"
    local key = plugin_path .. "|" .. subject
    if graph_cache[key] then return graph_cache[key] end
    local data, err = read_json(plugin_path .. "/data/knowledge/" .. subject .. "_graph.json")
    if not data then return nil, err end
    if type(data.nodes) ~= "table" or type(data.edges) ~= "table" then
        return nil, "graph missing nodes/edges"
    end

    local nodes, order, index = {}, {}, {}
    for i, node in ipairs(data.nodes) do
        if type(node.id) == "string" and not nodes[node.id] then
            nodes[node.id] = node
            table.insert(order, node.id)
            index[node.id] = i
        end
    end
    local prereqs, dependents = {}, {}
    for id in pairs(nodes) do
        prereqs[id] = {}
        dependents[id] = {}
    end
    for _, edge in ipairs(data.edges) do
        if nodes[edge.from] and nodes[edge.to] then
            table.insert(prereqs[edge.from], {
                id = edge.to,
                strength = edge.strength == "soft" and "soft" or "hard",
                reason = edge.reason,
            })
            table.insert(dependents[edge.to], { id = edge.from, strength = edge.strength })
        end
    end
    -- Hard prerequisites first, ties keep source file order (deterministic).
    for id, list in pairs(prereqs) do
        table.sort(list, function(a, b)
            local ra = (a.strength == "hard" and 0 or 1) * 100000 + (index[a.id] or 0)
            local rb = (b.strength == "hard" and 0 or 1) * 100000 + (index[b.id] or 0)
            return ra < rb
        end)
    end

    local graph = {
        subject = subject,
        nodes = nodes,
        order = order,
        index = index,
        prereqs = prereqs,
        dependents = dependents,
        edges = data.edges,
    }
    graph_cache[key] = graph
    return graph
end

--[[--
Load one volume (grade + semester) of a subject.
@treturn table {units, topics, questions, by_topic, skipped} or nil, err
--]]--
function Knowledge.load(plugin_path, subject, grade, semester)
    if not plugin_path or plugin_path == "" then return nil, "plugin path missing" end
    subject = subject or "math"
    grade = tonumber(grade) or 1
    semester = semester == "lower" and "lower" or "upper"
    local key = table.concat({ plugin_path, subject, tostring(grade), semester }, "|")
    if volume_cache[key] then return volume_cache[key] end

    local data, err = read_json(volume_path(plugin_path, subject, grade, semester))
    if not data then return nil, err end
    if type(data.topics) ~= "table" or type(data.questions) ~= "table" then
        return nil, "volume missing topics/questions"
    end

    local topics, topic_ids = {}, {}
    for _, topic in ipairs(data.topics) do
        if type(topic.id) == "string" and topic.id ~= "" then
            table.insert(topics, topic)
            topic_ids[topic.id] = true
        end
    end

    local questions, by_topic = {}, {}
    for _, topic in ipairs(topics) do by_topic[topic.id] = {} end
    local skipped = 0
    for _, raw in ipairs(data.questions) do
        local q, qerr = normalize_question(raw)
        if q and topic_ids[q.topic] then
            table.insert(questions, q)
            table.insert(by_topic[q.topic], q)
        else
            skipped = skipped + 1
            logger.warn("KidLearn: skipped knowledge question", raw and raw.id, qerr)
        end
    end
    if #questions == 0 then return nil, "no valid questions" end
    if skipped > 0 then
        logger.warn("KidLearn: skipped", skipped, "invalid knowledge questions in", subject, grade, semester)
    end

    local volume = {
        subject = subject,
        grade = grade,
        semester = semester,
        units = data.units or {},
        topics = topics,
        questions = questions,
        by_topic = by_topic,
        skipped = skipped,
    }
    volume_cache[key] = volume
    return volume
end

function Knowledge.topics(plugin_path, subject, grade, semester)
    local volume, err = Knowledge.load(plugin_path, subject, grade, semester)
    if not volume then return nil, err end
    return volume.topics
end

--[[--
Resolve a topic id to its full metadata (description, mastery criteria, example).
@treturn table topic metadata or nil
--]]--
function Knowledge.topic(plugin_path, subject, topic_id)
    local graph = Knowledge.graph(plugin_path, subject)
    if not graph then return nil end
    local node = graph.nodes[topic_id]
    if not node then return nil end
    local volume = Knowledge.load(plugin_path, subject, node.grade, node.semester)
    if not volume then return nil end
    for _, topic in ipairs(volume.topics) do
        if topic.id == topic_id then return topic end
    end
    return nil
end

--[[--
All synced questions for one topic (may cross volumes via the graph lookup).
@treturn table list of questions (possibly empty)
--]]--
function Knowledge.questions_for(plugin_path, subject, topic_id)
    local graph = Knowledge.graph(plugin_path, subject)
    if not graph then return {} end
    local node = graph.nodes[topic_id]
    if not node then return {} end
    local volume = Knowledge.load(plugin_path, subject, node.grade, node.semester)
    if not volume then return {} end
    return volume.by_topic[topic_id] or {}
end

function Knowledge.prereqs(plugin_path, subject, topic_id)
    local graph = Knowledge.graph(plugin_path, subject)
    if not graph then return {} end
    return graph.prereqs[topic_id] or {}
end

function Knowledge.dependents(plugin_path, subject, topic_id)
    local graph = Knowledge.graph(plugin_path, subject)
    if not graph then return {} end
    return graph.dependents[topic_id] or {}
end

--[[--
Judge an answer for a knowledge question.

Choice answers compare the 1-based option index.  Numeric answers use
answer_format: integer (exact), decimal (1e-9 tolerance), fraction (exact
cross-multiplication; an equivalent decimal input such as 0.5 for 1/2 is also
accepted).
--]]--
function Knowledge.judge(question, value)
    if type(question) ~= "table" then return false end
    if question.answer_mode ~= "number" then
        return tonumber(value) == question.answer
    end
    local format = question.answer_format
    if format == "fraction" then
        local anum, aden = tostring(question.answer):match("^(%d+)/(%d+)$")
        if not anum then return false end
        anum, aden = tonumber(anum), tonumber(aden)
        local vnum, vden = tostring(value or ""):match("^(%d+)/(%d+)$")
        if vnum then
            vnum, vden = tonumber(vnum), tonumber(vden)
            if vden == 0 then return false end
            return anum * vden == vnum * aden
        end
        local v = tonumber(value)
        if not v then return false end
        return math.abs(anum / aden - v) < 1e-9
    end
    local v = tonumber(value)
    if not v then return false end
    if format == "decimal" then
        return math.abs(v - question.answer) < 1e-9
    end
    return v == question.answer
end

function Knowledge.clear_cache()
    graph_cache = {}
    volume_cache = {}
end

Knowledge.normalize_question = normalize_question

return Knowledge
