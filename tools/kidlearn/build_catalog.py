def chinese_grades():
    grades = {}
    for grade, semesters in CHINESE_UNITS.items():
        g = {}
        for semester, units in semesters.items():
            g[semester] = {
                "file": f"chinese/tongbian/g{grade}_{semester}.json",
                "units": [
                    {"id": f"u{i}", "name": name, "topics": topics}
                    for i, (name, topics) in enumerate(units, 1)
                ],
            }
        grades[str(grade)] = g
    return grades


def math_grades(edition):
    grades = {}
    name_map = EDITION_NAME_MAP.get(edition, {})
    for grade, semesters in MATH_UNITS.items():
        g = {}
        for semester, units in semesters.items():
            out = []
            for i, (name, skills) in enumerate(units, 1):
                out.append({
                    "id": f"m{i}",
                    "name": name_map.get(name, name),
                    "skills": skills,
                })
            g[semester] = {"units": out}
        grades[str(grade)] = g
    return grades


