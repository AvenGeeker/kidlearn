def build_semester(grade, sem):
    units = GRADE_CHARS[grade][sem]
    pools = pools_for_grade(grade)
    semester_letter = "u" if sem == "upper" else "l"
    questions = []
    first_topics = []
    from build_catalog import CHINESE_UNITS
    for idx, (unit_id, _) in enumerate(units.items()):
        name, topics = CHINESE_UNITS[grade][sem][idx]
        first_topics.append(topics.split("、")[0])
    for ui, (unit_id, items) in enumerate(units.items()):
        rng = random.Random(f"kidlearn-{grade}-{sem}-{unit_id}")
        qn = 0
        name, topics = CHINESE_UNITS[grade][sem][ui]
        # 3 pinyin -> character
        for i, (char, py, word) in enumerate(items[:3]):
            py = py or pinyin_of(char, word)
            word = word or char
            qn += 1
            hint = f"提示：可以组成“{word}”。" if word and word != char else f"提示：这是本单元第{i + 1}个生字。"
            q = add_choice(
                f"zh{grade}{semester_letter}-{unit_id}-{qn:03d}", unit_id,
                "pinyin_to_char", "pinyin", DIFF_PINYIN[i],
                f"“{py}”对应的汉字是？{hint}", char, pinyin_options(char),
                f"“{char}”读 {py}，可以组词“{word}”。", rng,
            )
            questions.append(q)
        # 3 character -> pinyin
        for i, (char, py, word) in enumerate(items[:3]):
            py = py or pinyin_of(char, word)
            word = word or char
            qn += 1
            if word and word != char:
                stem = f"在“{word}”中，“{char}”的正确读音是？"
            else:
                stem = f"“{char}”的正确读音是？"
            q = add_choice(
                f"zh{grade}{semester_letter}-{unit_id}-{qn:03d}", unit_id,
                "char_to_pinyin", "pinyin", DIFF_PINYIN_REV[i],
                stem, py, char_pinyin_options(py),
                f"“{char}”读 {py}。", rng,
            )
            questions.append(q)
        word_sets = [
            (pools["measure"][ui % len(pools["measure"])], "measure_word" if grade <= 2 else "word_choice", "word", 1),
            (pools["synonym"][ui % len(pools["synonym"])], "synonym", "word", 1),
            (pools["antonym"][ui % len(pools["antonym"])], "antonym", "word", 2),
            (pools["sentence"][ui % len(pools["sentence"])], "sentence_choice", "sentence", 2),
            (pools["word"][(ui + 3) % len(pools["word"])], "word_choice", "word", 3),
        ]
        for (stem, correct, distractors, explain), qtype, skill, diff in word_sets:
            qn += 1
            questions.append(add_choice(
                f"zh{grade}{semester_letter}-{unit_id}-{qn:03d}", unit_id,
                qtype, skill, diff, stem, correct, distractors, explain, rng,
            ))
        comprehensive_sets = [
            (pools["synonym"][(ui + 1) % len(pools["synonym"])], "synonym", "word", 1),
            (pools["sentence"][(ui + 1) % len(pools["sentence"])], "sentence_choice", "sentence", 2),
            (pools["word"][(ui + 1) % len(pools["word"])], "word_choice", "word", 2),
        ]
        for (stem, correct, distractors, explain), qtype, skill, diff in comprehensive_sets:
            qn += 1
            questions.append(add_choice(
                f"zh{grade}{semester_letter}-{unit_id}-{qn:03d}", unit_id,
                qtype, skill, diff, stem, correct, distractors, explain, rng,
            ))
        for i in range(4):
            item = pools["accum"][(ui * 4 + i) % len(pools["accum"])]
            qn += 1
            if isinstance(item, dict):
                stem, correct, distractors, explain = item["stem"], item["correct"], item["distractors"], item["explain"]
            else:
                stem, correct, distractors, explain = item
            questions.append(add_choice(
                f"zh{grade}{semester_letter}-{unit_id}-{qn:03d}", unit_id,
                "accumulation", "accumulation", DIFF_ACCUM[i],
                stem, correct, distractors, explain, rng,
            ))
        passage, r1, r2 = reading_for(grade, ui, name, topics)
        for i, (stem, correct, distractors, explain) in enumerate((r1, r2)):
            qn += 1
            questions.append(add_choice(
                f"zh{grade}{semester_letter}-{unit_id}-{qn:03d}", unit_id,
                "reading", "reading", DIFF_READING[i],
                stem, correct, distractors, explain, rng, passage=passage,
            ))
        assert qn == 20, (grade, sem, unit_id, qn)
    return questions


def main():
    if pinyin is None:
        raise SystemExit("pypinyin is required to build grades 1-6; run: pip install -r tools/kidlearn/requirements.txt")
    OUT.mkdir(parents=True, exist_ok=True)
    total = 0
    for grade in range(1, 7):
        for sem in ("upper", "lower"):
            data = {
                "schema_version": 1,
                "subject": "chinese",
                "grade": grade,
                "semester": sem,
                "textbook": "统编版",
                "questions": build_semester(grade, sem),
            }
            path = OUT / f"g{grade}_{sem}.json"
            path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            total += len(data["questions"])
            print(f"wrote {path} ({len(data['questions'])} questions)")
    print(f"total {total} questions")


if __name__ == "__main__":
    main()
