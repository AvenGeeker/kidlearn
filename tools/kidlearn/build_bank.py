DIFF_PINYIN = [1, 1, 1]
DIFF_PINYIN_REV = [1, 1, 2]
DIFF_ACCUM = [2, 2, 2, 3]
DIFF_READING = [3, 3]


def pinyin_of(char, word=None):
    if char in PINYIN_OVERRIDES:
        return PINYIN_OVERRIDES[char]
    if pinyin is None:
        return char
    text = word if word and char in word else char
    try:
        values = pinyin(text, style=Style.TONE, heteronym=False)
        index = text.index(char) if char in text else 0
        return values[index][0]
    except Exception:
        return char


def all_char_triples():
    for grade, semesters in GRADE_CHARS.items():
        for units in semesters.values():
            for items in units.values():
                for char, py, word in items:
                    yield char, py or pinyin_of(char, word), word or char


ALL = list(all_char_triples())
ALL_PINYIN = sorted({py for _, py, _ in ALL})
CHAR_TO_PINYIN = {char: py for char, py, _ in ALL}


def make_options(correct, distractors, rng):
    opts = [correct]
    seen = {correct}
    for d in distractors:
        if d not in seen:
            seen.add(d)
            opts.append(d)
        if len(opts) == 4:
            break
    while len(opts) < 4:
        candidate = ALL_PINYIN[rng.randrange(len(ALL_PINYIN))]
        if candidate not in seen:
            seen.add(candidate)
            opts.append(candidate)
    rng.shuffle(opts)
    return opts, opts.index(correct) + 1


def add_choice(qid, unit, qtype, skill, diff, stem, correct, distractors, explain, rng, passage=None):
    options, answer = make_options(correct, distractors, rng)
    q = {
        "id": qid,
        "unit": unit,
        "type": qtype,
        "skill": skill,
        "difficulty": diff,
        "answer_mode": "choice",
        "stem": stem,
        "options": options,
        "answer": answer,
        "explain": explain,
    }
    if passage:
        q["passage"] = passage
    return q


def pinyin_options(correct_char):
    correct_py = CHAR_TO_PINYIN.get(correct_char)
    candidates = [c for c, py, _ in ALL if c != correct_char and py != correct_py]
    seen = set()
    out = []
    for c in candidates:
        py = CHAR_TO_PINYIN[c]
        if py not in seen:
            seen.add(py)
            out.append(c)
        if len(out) == 3:
            break
    return out


def char_pinyin_options(correct_pinyin):
    seen = {correct_pinyin}
    out = []
    for py in ALL_PINYIN:
        if py not in seen:
            seen.add(py)
            out.append(py)
        if len(out) == 3:
            break
    return out


def pools_for_grade(grade):
    if grade == 1:
        return {
            "measure": MEASURE,
            "synonym": EASY_SYNONYM,
            "antonym": EASY_ANTONYM,
            "sentence": EASY_SENTENCE,
            "word": EASY_WORD,
            "accum": ACCUM_ITEMS,
        }
    if grade == 2:
        return {
            "measure": MEASURE,
            "synonym": SYNONYM,
            "antonym": ANTONYM,
            "sentence": SENTENCE,
            "word": WORD_HARD,
            "accum": ACCUM_ITEMS,
        }
    if grade <= 4:
        return {
            "measure": ADV_WORD,
            "synonym": ADV_SYNONYM,
            "antonym": ADV_ANTONYM,
            "sentence": ADV_SENTENCE,
            "word": ADV_WORD,
            "accum": ADV_ACCUM,
        }
    return {
        "measure": HIGH_WORD,
        "synonym": HIGH_SYNONYM,
        "antonym": HIGH_ANTONYM,
        "sentence": HIGH_SENTENCE,
        "word": HIGH_WORD,
        "accum": HIGH_ACCUM,
    }


